# # Используя конструкцию match-case решите задачу своего варианта.
# # Напишите программу, которая классифицирует месяц по сезону: 
# # Январь, февраль, декабрь — "Зима". 
# # Март, апрель, май — "Весна".
# # Июнь, июль, август — "Лето". 
# # Сентябрь, октябрь, ноябрь — "Осень". 
# # Выведите ошибку, если введен неправильный месяц.

match input("введите месяц"):
    case "январь" | "февраль" | "декабрь":
        print("зима")
    case "март" | "апрель" | "май":
        print("весна")
    case "июнь" | "июль" | "август":
        print("лето")
    case "сентябрь" | "октябрь" | "ноябрь":
        print("осень")
    case _: print("месяц введен неверно")

