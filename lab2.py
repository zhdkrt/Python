# #task1
# # Используя конструкцию if-else-elif решите задачу своего варианта.
# # Определите, является ли число чётным и больше ли оно 100. Выведите соответствующие сообщения.

num = int(input("введите число: "))

if num % 2 == 0 & num > 100:
    print("число четное и больше 100")
elif num % 2 != 0 & num > 100:
    print("число нечетное и больше 100")
elif num % 2 == 0 & num < 100:
    print("число четное и меньше 100")
elif num % 2 != 0 & num < 100:
    print("число нечетное и меньше 100")
else:
    print("число четное и равно 100")

