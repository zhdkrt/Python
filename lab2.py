# Используя конструкцию while и continue с break решите задачу своего варианта. 
# Напишите программу, которая использует цикл while для нахождения всех чисел от 1 до N,
# которые не делятся на 3 и 5.

n = int(input("введите границу: "))
count = 1

while count <= n:
    if n <= count:
        break
    elif count % 3 != 0 and count % 5 != 0:
        print(count, end = " ")
    count += 1

